using System.Buffers.Binary;
using System.Text;
using Capsule.Assets;
using Capsule.Build.Registry;

namespace Capsule.Build.Strings;

/// <summary>
/// Writes <c>CapsuleStrings.g.cs</c>: a <c>TextKey</c> member per source text and a <c>TextList</c> per source
/// list, nested in a class per group, and the table holding every language's texts as UTF-8 data.
/// </summary>
/// <remarks>
/// Each language is one UTF-8 literal and a span of each key's exclusive end in it, both read from the
/// assembly's data with no allocation. The plural rules of the shipped languages compile to one method,
/// and no other language's rules ship. The text is the same on every machine whatever order the files
/// were read in.
/// </remarks>
internal static class StringsMembers
{
    internal const string FileName = "CapsuleStrings.g.cs";

    private const string Root = "CapsuleStrings";

    private const string TextKey = "global::Capsule.Localization.TextKey";

    private const string TextList = "global::Capsule.Localization.TextList";

    private const string StringTable = "global::Capsule.Localization.StringTable";

    private const string Span = "global::System.ReadOnlySpan";

    // The members CapsuleStrings declares itself, which no root key may become.
    private static readonly string[] Reserved = ["Languages", "Table"];

    /// <summary>The C# text, or null when a key becomes a name C# would refuse, each refusal reported.</summary>
    /// <param name="languages">The shipped tags: the source first, then the rest in ordinal order.</param>
    /// <param name="fallback">The index in <paramref name="languages"/> of the fallback language.</param>
    /// <param name="texts">Each language's resolved texts, in key order.</param>
    /// <param name="keys">Each source text's key path, defining file, authored text, argument count and the arguments a plural selects on, in key order.</param>
    /// <param name="lists">Each source list's key path, defining file, first key and count, in key order.</param>
    internal static string? Render(
        PipelinePass pass,
        string[] languages,
        int fallback,
        string[][] texts,
        (string Path, string File, string Text, int Arguments, byte Plurals)[] keys,
        (string Path, string File, int First, int Count)[] lists)
    {
        Group root = new(Root, string.Empty);
        bool refused = false;
        int list = 0;
        for (int i = 0; i < keys.Length; i++)
        {
            // A list declares one member for its texts.
            (string path, string file, int count) = list < lists.Length && lists[list].First == i
                ? (lists[list].Path, lists[list].File, lists[list++].Count)
                : (keys[i].Path, keys[i].File, 0);
            if (root.Add(path, i, count) is { } because)
            {
                pass.Fail(file, $"{path}: {because}");
                refused = true;
            }

            i += Math.Max(count - 1, 0);
        }

        if (refused)
        {
            return null;
        }

        StringBuilder code = new();
        code.Append("""
            // <auto-generated/>
            #nullable enable

            namespace Capsule.Generated
            {
                /// <summary>Every text this game ships, keyed as its source language authors it. Generated code.</summary>
                [global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]
                public static class CapsuleStrings
                {
                    /// <summary>The languages this game ships, as BCP 47 tags: the source language first, then the rest in ordinal order.</summary>
                    public static global::System.ReadOnlySpan<string> Languages => CapsuleStringTable.Tags;

                    /// <summary>Every language's texts, which the engine reads. Generated code.</summary>
                    [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]
                    public static global::Capsule.Localization.StringTable Table { get; } = new CapsuleStringTable();

            """);
        root.AppendMembers(code, "        ", keys);
        code.AppendLine("    }").AppendLine();

        code.AppendLine("    /// <summary>The texts <c>CapsuleStrings.Table</c> holds. Generated code.</summary>");
        code.AppendLine("    [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
        code.AppendLine("    [global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]");
        code.Append("    internal sealed class CapsuleStringTable : ").AppendLine(StringTable);
        code.AppendLine("    {");
        code.Append("        internal static readonly string[] Tags = [").AppendJoin(", ", languages.Select(Literal.Of)).AppendLine("];");
        code.AppendLine();
        code.Append("        internal CapsuleStringTable()").AppendLine();
        code.Append("            : base(Tags, ").Append(Literal.Of(fallback)).AppendLine(")");
        code.AppendLine("        {");
        code.AppendLine("        }");
        code.AppendLine();
        code.Append("        protected override ").Append(Span).AppendLine("<byte> ArgumentCounts => Counts;");
        code.AppendLine();
        code.Append("        protected override ").Append(Span).AppendLine("<byte> PluralArguments => Plurals;");
        code.AppendLine();
        code.Append("        protected override ").Append(Span).AppendLine("<byte> SortedKeys => KeyOrder;");
        code.AppendLine();
        code.Append("        protected override ").Append(Span).Append("<byte> GetText(int language, out ").Append(Span).AppendLine("<byte> ends)");
        code.AppendLine("        {");
        code.AppendLine("            switch (language)");
        code.AppendLine("            {");
        for (int language = 0; language < languages.Length; language++)
        {
            code.Append("                case ").Append(Literal.Of(language)).AppendLine(":");
            code.Append("                    ends = Ends").Append(Literal.Of(language)).AppendLine(";");
            code.Append("                    return ").Append(Literal.Of(string.Concat(texts[language]))).AppendLine("u8;");
        }

        code.AppendLine("                default:");
        code.AppendLine("                    throw new global::System.ArgumentOutOfRangeException(nameof(language));");
        code.AppendLine("            }");
        code.AppendLine("        }");
        code.AppendLine();
        code.Append("        protected override ").Append(Span).Append("<byte> GetKeyPaths(out ").Append(Span).AppendLine("<byte> ends)");
        code.AppendLine("        {");
        code.AppendLine("            ends = KeyEnds;");
        code.Append("            return ").Append(Literal.Of(string.Concat(keys.Select(static key => key.Path)))).AppendLine("u8;");
        code.AppendLine("        }");

        code.AppendLine();
        Categories(code, languages);

        // Every text and table is a span over constant bytes, read from the assembly's data with no
        // allocation in any configuration. The offsets are little-endian 32-bit integers.
        Bytes(code, "Counts", keys.Select(static key => (byte)key.Arguments));
        Bytes(code, "Plurals", keys.Select(static key => key.Plurals));
        Ends(code, "KeyEnds", keys.Select(static key => key.Path));
        Order(code, keys);
        for (int language = 0; language < languages.Length; language++)
        {
            Ends(code, "Ends" + Literal.Of(language), texts[language]);
        }

        code.AppendLine("    }");
        code.AppendLine("}");

        return code.ToString();
    }

    // The category each shipped language's rules select for a count, languages with the same rules sharing one case.
    private static void Categories(StringBuilder code, string[] languages)
    {
        code.Append("        protected override global::Capsule.Localization.PluralCategory SelectCategory(int language, ulong count)").AppendLine();
        code.AppendLine("        {");
        code.AppendLine("            switch (language)");
        code.AppendLine("            {");
        foreach (IGrouping<string, int> shared in Enumerable.Range(0, languages.Length).GroupBy(language => Rules(languages[language])))
        {
            foreach (int language in shared)
            {
                code.Append("                case ").Append(Literal.Of(language)).Append(": // ").AppendLine(languages[language]);
            }

            code.AppendLine("                {");
            code.Append(shared.Key);
            code.AppendLine("                }");
            code.AppendLine();
        }

        code.AppendLine("                default:");
        code.AppendLine("                    throw new global::System.ArgumentOutOfRangeException(nameof(language));");
        code.AppendLine("            }");
        code.AppendLine("        }");
    }

    // A language's rules as the statements of its case. A language the CLDR has no rules for selects other.
    private static string Rules(string language)
    {
        StringBuilder statements = new();
        if (PluralRules.For(language) is { } rules)
        {
            rules.Write(statements, "                    ", "count");
        }
        else
        {
            statements.AppendLine("                    return global::Capsule.Localization.PluralCategory.Other;");
        }

        return statements.ToString();
    }

    // Every key index in ordinal order of its path's UTF-8 bytes, which the table's search compares.
    private static void Order(StringBuilder code, (string Path, string File, string Text, int Arguments, byte Plurals)[] keys)
    {
        byte[][] paths = [.. keys.Select(static key => Encoding.UTF8.GetBytes(key.Path))];
        int[] order = [.. Enumerable.Range(0, keys.Length)];
        Array.Sort(order, (left, right) => paths[left].AsSpan().SequenceCompareTo(paths[right]));
        byte[] bytes = new byte[order.Length * sizeof(int)];
        for (int i = 0; i < order.Length; i++)
        {
            BinaryPrimitives.WriteInt32LittleEndian(bytes.AsSpan(i * sizeof(int)), order[i]);
        }

        Bytes(code, "KeyOrder", bytes);
    }

    private static void Ends(StringBuilder code, string name, IEnumerable<string> texts)
    {
        int end = 0;
        List<byte> bytes = [];
        foreach (string text in texts)
        {
            end += Encoding.UTF8.GetByteCount(text);
            byte[] offset = new byte[sizeof(int)];
            BinaryPrimitives.WriteInt32LittleEndian(offset, end);
            bytes.AddRange(offset);
        }

        Bytes(code, name, bytes);
    }

    private static void Bytes(StringBuilder code, string name, IEnumerable<byte> bytes) =>
        code.AppendLine().Append("        private static ").Append(Span).Append("<byte> ").Append(name).Append(" => [")
            .AppendJoin(", ", bytes.Select(static value => Literal.Of(value))).AppendLine("];");

    // A text's summary: the authored text in quotes, one comment line per line of it.
    private static string Summary(string text, string indent) =>
        "\"" + text.Replace("&", "&amp;", StringComparison.Ordinal).Replace("<", "&lt;", StringComparison.Ordinal).Replace(">", "&gt;", StringComparison.Ordinal)
            .Replace("\n", "\n" + indent + "/// ", StringComparison.Ordinal) + "\"";

    // One group as a class: its texts, lists and nested groups, in key order.
    private sealed class Group(string identifier, string path)
    {
        // A text's or list's first key and a list's count, else the nested group.
        private readonly List<(Group? Group, int Key, int Count)> _members = [];

        private readonly Dictionary<string, Group> _groups = new(StringComparer.Ordinal);

        // The key path that already takes each identifier here.
        private readonly Dictionary<string, string> _claimedBy = new(StringComparer.Ordinal);

        private string Identifier { get; } = identifier;

        private string KeyPath { get; } = path;

        // Declares the text at index, or the list of count texts from it, under its path, creating each group
        // class it walks through. Null when declared, else why C# would refuse it.
        internal string? Add(string keyPath, int index, int count)
        {
            Group group = this;
            string[] names = keyPath.Split('.');
            for (int i = 0; i < names.Length; i++)
            {
                string prefix = string.Join('.', names, 0, i + 1);
                if (AssetPaths.ToIdentifier(names[i]) is not { } name)
                {
                    return $"has \"{names[i]}\", which makes no C# name. A key's names are letters, digits, '-' and '_', and do not start with a digit.";
                }

                if (name == group.Identifier)
                {
                    return $"becomes '{name}' inside the class of that name, which C# refuses. Rename the key or its group.";
                }

                if (group == this && Reserved.Contains(name))
                {
                    return $"becomes '{name}', which {Root} declares itself. Rename the key.";
                }

                if (group._claimedBy.TryGetValue(name, out string? claimant)
                    && !(i < names.Length - 1 && claimant == prefix))
                {
                    return $"becomes '{name}', which '{claimant}' already takes. Two keys differing only in case or separators are one C# name. Rename one.";
                }

                if (i == names.Length - 1)
                {
                    group._claimedBy.Add(name, prefix);
                    group._members.Add((null, index, count));
                }
                else if (!group._groups.TryGetValue(name, out Group? child))
                {
                    child = new Group(name, prefix);
                    group._groups.Add(name, child);
                    group._claimedBy.Add(name, prefix);
                    group._members.Add((child, -1, 0));
                    group = child;
                }
                else
                {
                    group = child;
                }
            }

            return null;
        }

        internal void AppendMembers(StringBuilder code, string indent, (string Path, string File, string Text, int Arguments, byte Plurals)[] keys)
        {
            bool first = true;
            foreach ((Group? group, int key, int count) in _members)
            {
                if (!first)
                {
                    code.AppendLine();
                }

                first = false;
                if (group is not null)
                {
                    code.Append(indent).Append("/// <summary>Every text keyed under <c>").Append(group.KeyPath).AppendLine("</c>.</summary>");
                    code.Append(indent).Append("public static class ").AppendLine(group.Identifier);
                    code.Append(indent).AppendLine("{");
                    group.AppendMembers(code, indent + "    ", keys);
                    code.Append(indent).AppendLine("}");
                    continue;
                }

                (string path, _, string text, _, _) = keys[key];
                if (count > 0)
                {
                    // A list is named for its own key, its first text's path less the position.
                    path = path[..path.LastIndexOf('.')];
                }

                string name = AssetPaths.ToIdentifier(path[(path.LastIndexOf('.') + 1)..])!;
                code.Append(indent).Append("/// <summary>").Append(Summary(text, indent));
                code.AppendLine(count > 1 ? $" and {Literal.Of(count - 1)} more.</summary>" : "</summary>");
                code.Append(indent).Append("public static ").Append(count > 0 ? TextList : TextKey).Append(' ').Append(name)
                    .Append(" => new(global::Capsule.Generated.CapsuleStrings.Table, ").Append(Literal.Of(key));
                code.AppendLine(count > 0 ? $", {Literal.Of(count)});" : ");");
            }
        }
    }
}
